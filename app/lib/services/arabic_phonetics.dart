class AffixUse {
  final String how; // 쓰임
  final String ex; // 예(타슈킬 없음)
  final String exRd;
  final String exKo;
  const AffixUse(this.how, this.ex, this.exRd, this.exKo);
}

class AffixLetter {
  final String ch;
  final String name;
  final List<AffixUse> uses;
  const AffixLetter(this.ch, this.name, this.uses);
}

